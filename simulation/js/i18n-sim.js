let currentLang = 'en';

export function setSimLanguage(lang) {
  if (simTranslations[lang]) {
    currentLang = lang;
    document.querySelectorAll('[data-sim-i18n]').forEach(elem => {
      const key = elem.getAttribute('data-sim-i18n');
      if (simTranslations[currentLang][key]) {
        elem.textContent = simTranslations[currentLang][key];
      }
    });
  }
}

export function tSim(key) {
  return simTranslations[currentLang]?.[key] || simTranslations['en']?.[key] || key;
}
